// Declaración de variables
const init_vis = 100;
let total_vis;

// Cálculo de las visitas totales
total_vis = init_vis;
console .log("Las visitas iniciales son:", total_vis);

total_vis = total_vis + 25;
console .log("Después de ganar 25 visitas, el total es:", total_vis);

total_vis = total_vis - 10;
console .log("Después de perder 10 visitas, por un error de registro, el total es:", total_vis);

total_vis = total_vis * 2;
console .log("Después de que el sitio duplique sus visitas, el total es:", total_vis);

